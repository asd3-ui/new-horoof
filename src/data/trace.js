/** مسار شكل يقوم بنفس فكرة الحروف: نقاط مت Nhالتة حول محيط الشكل */
function polygonGuide(points) {
  return { strokes: [points.map((pair) => pair.slice())] };
}

function ellipseGuide(rx, ry, steps = 14, startAngle = -110) {
  const points = [];
  for (let i = 0; i <= steps; i += 1) {
    const angle = ((startAngle + (360 / steps) * i) * Math.PI) / 180;
    const x = 50 + Math.cos(angle) * rx;
    const y = 50 + Math.sin(angle) * ry;
    points.push([Number(x.toFixed(1)), Number(y.toFixed(1))]);
  }
  return { strokes: [points] };
}

